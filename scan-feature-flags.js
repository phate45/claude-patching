#!/usr/bin/env node
/**
 * scan-feature-flags.js — Extract and diff GrowthBook feature flags from a cli.js bundle
 *
 * Parses every Bun chunk with acorn, resolves bindings with eslint-scope, and
 * finds the flag accessors by structure: functions whose parameter reaches a
 * GrowthBook client method (`getFeatureValue*`, `checkGate*`), plus the wrappers
 * around them, followed across chunks. Every call to an accessor is a flag read;
 * its name argument is evaluated statically, so names held in constants, built
 * from templates, picked by a conditional, or read out of a constant table are
 * all found. Nothing is matched by minified name.
 *
 * Reads the scanner cannot resolve (names computed at runtime, accessors invoked
 * as callbacks) are reported as `unresolved`, with locations, instead of being
 * dropped. One known blind spot: an accessor stored on an object and read back
 * (`registry.reader("tengu_…")`) is invisible — that is heap flow, not scope.
 *
 * Usage:
 *   node scan-feature-flags.js <.pretty>                              # Print all flags
 *   node scan-feature-flags.js <.pretty> --save <inventory.json>     # Save inventory
 *   node scan-feature-flags.js <.pretty> --diff <prev-inventory.json># Diff vs previous
 *   node scan-feature-flags.js <.pretty> --save <out.json> --diff <prev.json>  # Both
 *
 * Input: cli.js.<type>.pretty or .original — generated by --setup. The .original
 * is always the one parsed; line numbers are reported against the .pretty.
 * Output: NDJSON — one JSON object per line, last line is the summary.
 * Inventory files (--save) are plain JSON, suitable for --diff in a later run.
 *
 * Intended integration: called during --port to generate a per-version flag snapshot
 * and automatically diff against the previous version's snapshot. Inventories
 * made before the AST scanner (2.1.280 and earlier, except 2.1.280 itself) only
 * cover direct gate calls, so a diff against one reports many long-standing
 * flags as added.
 */

'use strict';

const fs = require('fs');
const acorn = require('acorn');
const eslintScope = require('eslint-scope');

// ---------------------------------------------------------------------------
// Argument parsing
// ---------------------------------------------------------------------------

const args = process.argv.slice(2);

function consumeArg(flag) {
  const idx = args.indexOf(flag);
  if (idx === -1) return null;
  const val = args[idx + 1];
  args.splice(idx, 2);
  return val ?? true;
}

const saveFile = consumeArg('--save');
const diffFile = consumeArg('--diff');
const targetPath = args.find(a => !a.startsWith('--'));

if (!targetPath) {
  process.stderr.write(JSON.stringify({ type: 'error', message: 'Usage: scan-feature-flags.js <.pretty> [--save <file>] [--diff <prev.json>]' }) + '\n');
  process.exit(1);
}

// ---------------------------------------------------------------------------
// Output helpers (inline — no dep on lib/output.js for standalone use)
// ---------------------------------------------------------------------------

function emit(obj) {
  process.stdout.write(JSON.stringify(obj) + '\n');
}

// ---------------------------------------------------------------------------
// Load source
//
// Parsing needs the exact extract (.original). js-beautify is not a faithful
// transform: it loses track of some regex literals and inserts whitespace into
// the template literals that follow, so a .pretty file does not always parse.
// Line numbers are still reported against .pretty, since that is the file you
// read. Either file can be passed; the other is picked up as a sibling.
// ---------------------------------------------------------------------------

function readOrExit(file) {
  try {
    return fs.readFileSync(file, 'utf8');
  } catch (err) {
    emit({ type: 'error', message: `Cannot read ${file}: ${err.message}` });
    process.exit(1);
  }
}

const stem = targetPath.replace(/\.(pretty|original)$/, '');
const originalPath = /\.pretty$/.test(targetPath) ? `${stem}.original` : targetPath;
const prettyPath = /\.pretty$/.test(targetPath) ? targetPath : `${stem}.pretty`;

if (!fs.existsSync(originalPath)) {
  emit({ type: 'error', message: `Cannot find ${originalPath} — the scanner parses the unbeautified extract (run --setup)` });
  process.exit(1);
}
const content = readOrExit(originalPath);
const prettyContent = prettyPath !== originalPath && fs.existsSync(prettyPath) ? readOrExit(prettyPath) : null;

// ---------------------------------------------------------------------------
// Split into chunks
//
// Since 2.1.246 the bundle is ~2000 separately-scoped Bun chunk modules, each
// opening with a `// @bun` header line. The extracted file is their plain
// concatenation, so the headers are exact boundaries. Chunks redeclare each
// other's names (a minified `Oa` exists in several), so each is parsed on its
// own. Pre-2.1.246 bundles have a single header and come out as one chunk.
// ---------------------------------------------------------------------------

// js-beautify indents some headers, hence the leading-whitespace allowance.
function splitChunks(text) {
  const starts = [...text.matchAll(/^[ \t]*\/\/ @bun/gm)].map(m => m.index);
  if (starts.length === 0 || starts[0] !== 0) starts.unshift(0);
  const out = [];
  let line = 1;
  let prev = 0;
  for (let i = 0; i < starts.length; i++) {
    const s = starts[i];
    const e = i + 1 < starts.length ? starts[i + 1] : text.length;
    for (let j = prev; j < s; j++) if (text.charCodeAt(j) === 10) line++;
    prev = s;
    out.push({ index: i, text: text.slice(s, e), startLine: line });
  }
  return out;
}

const chunks = splitChunks(content);
let prettyChunks = prettyContent ? splitChunks(prettyContent) : null;
if (prettyChunks && prettyChunks.length !== chunks.length) {
  emit({ type: 'warning', message: `${prettyPath} has ${prettyChunks.length} chunks, ${originalPath} has ${chunks.length} — reporting .original line numbers` });
  prettyChunks = null;
}

// Map a site in a chunk to a line number. `key` is source text that starts at
// `offset` and survives beautification (`callee(`, `function name`): the site
// is the key's Nth occurrence in the original chunk, so it is the Nth
// occurrence in the pretty chunk too. A site that cannot be mapped gets null.
const occurrenceCache = new Map();
function occurrences(text, key, cacheId) {
  const id = `${cacheId}\0${key}`;
  let list = occurrenceCache.get(id);
  if (!list) {
    list = [];
    for (let i = text.indexOf(key); i !== -1; i = text.indexOf(key, i + 1)) {
      if (!/[\w$]/.test(text[i - 1] ?? '')) list.push(i);
    }
    occurrenceCache.set(id, list);
  }
  return list;
}

// Zero-based line of `offset`, by binary search over the chunk's newline offsets.
const newlineCache = new Map();
function lineAt(text, offset, cacheId) {
  let nl = newlineCache.get(cacheId);
  if (!nl) {
    nl = [];
    for (let i = text.indexOf('\n'); i !== -1; i = text.indexOf('\n', i + 1)) nl.push(i);
    newlineCache.set(cacheId, nl);
  }
  let lo = 0, hi = nl.length;
  while (lo < hi) { const mid = (lo + hi) >> 1; if (nl[mid] < offset) lo = mid + 1; else hi = mid; }
  return lo;
}

const lineSource = prettyChunks ? 'pretty' : 'original';
let lineMapMisses = 0;
function siteLine(chunk, offset, key) {
  if (prettyChunks) {
    const nth = occurrences(chunk.text, key, `o${chunk.index}`).indexOf(offset);
    const pc = prettyChunks[chunk.index];
    const at = nth === -1 ? undefined : occurrences(pc.text, key, `p${chunk.index}`)[nth];
    if (at !== undefined) return pc.startLine + lineAt(pc.text, at, `p${chunk.index}`);
    lineMapMisses++;
    return null; // never an .original line in a .pretty-numbered inventory
  }
  return chunk.startLine + lineAt(chunk.text, offset, `o${chunk.index}`);
}

function parseChunk(chunk) {
  let firstError = null;
  for (const sourceType of ['module', 'script']) {
    try {
      const ast = acorn.parse(chunk.text, {
        ecmaVersion: 'latest', sourceType, ranges: true,
        allowHashBang: true, allowReturnOutsideFunction: sourceType === 'script',
      });
      const scopes = eslintScope.analyze(ast, {
        ecmaVersion: 2022, sourceType, fallback: 'iteration',
      });
      const refs = new Map(); // Identifier node → resolved Variable
      for (const scope of scopes.scopes) {
        for (const ref of scope.references) refs.set(ref.identifier, ref.resolved);
      }
      return { ast, scopes, refs };
    } catch (err) {
      firstError ??= err;
      if (sourceType === 'script') {
        emit({ type: 'error', message: `Cannot parse chunk ${chunk.index} (line ${chunk.startLine}): ${firstError.message}` });
        process.exit(1);
      }
    }
  }
}

// Iterative walk — minified string concatenation nests deep enough to blow the stack.
function eachNode(root, visit) {
  const stack = [root];
  while (stack.length) {
    const node = stack.pop();
    visit(node);
    for (const key in node) {
      if (key === 'loc') continue;
      const v = node[key];
      if (Array.isArray(v)) { for (let i = v.length - 1; i >= 0; i--) if (v[i] && typeof v[i].type === 'string') stack.push(v[i]); }
      else if (v && typeof v.type === 'string') stack.push(v);
    }
  }
}

const isFn = n => n && (n.type === 'FunctionDeclaration' || n.type === 'FunctionExpression' || n.type === 'ArrowFunctionExpression');

// The function node a variable is bound to, if it is bound to exactly one.
function boundFunction(variable) {
  if (!variable || variable.defs.length !== 1) return null;
  const def = variable.defs[0];
  if (def.type === 'FunctionName') return def.node;
  if (def.type === 'Variable' && isFn(def.node.init)) return def.node.init;
  return null;
}

// A variable's initialiser, when that is the only value it ever holds: one
// definition, a plain identifier binding, never reassigned.
function soleInit(variable) {
  if (!variable || variable.defs.length !== 1) return null;
  const def = variable.defs[0];
  if (def.type !== 'Variable' || !def.node.init || def.node.id.type !== 'Identifier') return null;
  if (variable.references.filter(r => r.isWrite()).length > 1) return null;
  return def.node.init;
}

function literalString(node) {
  if (!node) return null;
  if (node.type === 'Literal' && typeof node.value === 'string') return node.value;
  if (node.type === 'TemplateLiteral' && node.expressions.length === 0) return node.quasis[0].value.cooked;
  return null;
}

const stringConstant = variable => literalString(soleInit(variable));

// ---------------------------------------------------------------------------
// Name forms
//
// Wrappers do not always pass the flag name straight through. In 2.1.280 alone:
//   w(e, n) { … x(n, !1) }            name is the second parameter
//   r(e)    { … x(`tengu_${e}`, !1) }  name is a prefixed parameter
//   M(e)    { … x(e.flagName, !1) }    name is a property of the parameter
// A form records which parameter carries the name and how:
//   prefix + param[index] (or param[index][prop]) + suffix
// ---------------------------------------------------------------------------

// Which function parameter an identifier is, if it is one.
function paramOf(refs, ident) {
  const v = refs.get(ident);
  const def = v && v.defs.length === 1 ? v.defs[0] : null;
  if (!def || def.type !== 'Parameter' || def.rest) return null;
  let p = def.node.params[def.index];
  if (p?.type === 'AssignmentPattern') p = p.left;
  if (!p || p.type !== 'Identifier' || p.name !== ident.name) return null; // destructured
  return { fn: def.node, index: def.index };
}

// How an expression derives from a parameter of its function, or null.
function paramForm(refs, node) {
  if (!node) return null;
  if (node.type === 'Identifier') {
    const p = paramOf(refs, node);
    return p && { fn: p.fn, index: p.index, prefix: '', suffix: '', prop: null };
  }
  if (node.type === 'MemberExpression' && !node.computed && node.object.type === 'Identifier' && node.property.type === 'Identifier') {
    const p = paramOf(refs, node.object);
    return p && { fn: p.fn, index: p.index, prefix: '', suffix: '', prop: node.property.name };
  }
  if (node.type === 'TemplateLiteral' && node.expressions.length === 1) {
    const inner = paramForm(refs, node.expressions[0]);
    if (inner && !inner.prefix && !inner.suffix) {
      return { ...inner, prefix: node.quasis[0].value.cooked, suffix: node.quasis[1].value.cooked };
    }
  }
  return null;
}

const describeForm = f =>
  `${f.prefix ? `"${f.prefix}"+` : ''}arg${f.index}${f.prop ? `.${f.prop}` : ''}${f.suffix ? `+"${f.suffix}"` : ''}`;

// ---------------------------------------------------------------------------
// Static string evaluation
//
// Resolves a name argument to the set of strings it can be: literals, string
// constants (local or imported), both arms of a conditional, template and `+`
// concatenations, the return values of a local function (`Me = () => "…"`),
// and properties read out of constant object tables (`GD[Z].flag`). `complete`
// is false when some branch could not be followed.
// ---------------------------------------------------------------------------

const MAX_CANDIDATES = 64;
const FAIL = () => ({ values: new Set(), complete: false });
const single = s => ({ values: new Set([s]), complete: true });

function union(results) {
  const out = { values: new Set(), complete: true };
  for (const r of results) {
    for (const v of r.values) out.values.add(v);
    if (!r.complete) out.complete = false;
  }
  if (out.values.size > MAX_CANDIDATES) return FAIL();
  return out;
}

function concat(parts) {
  let acc = single('');
  for (const p of parts) {
    if (p.values.size === 0) return FAIL();
    const next = new Set();
    for (const a of acc.values) for (const b of p.values) next.add(a + b);
    if (next.size > MAX_CANDIDATES) return FAIL();
    acc = { values: next, complete: acc.complete && p.complete };
  }
  return acc;
}

// Return expressions of a function, not descending into nested functions.
function returnExpressions(fn) {
  if (fn.type === 'ArrowFunctionExpression' && fn.expression) return [fn.body];
  const out = [];
  const stack = [fn.body];
  while (stack.length) {
    const node = stack.pop();
    if (node.type === 'ReturnStatement') { if (node.argument) out.push(node.argument); continue; }
    for (const key in node) {
      const v = node[key];
      const kids = Array.isArray(v) ? v : [v];
      for (const k of kids) if (k && typeof k.type === 'string' && !isFn(k)) stack.push(k);
    }
  }
  return out;
}

function propertyKey(member) {
  if (!member.computed && member.property.type === 'Identifier') return member.property.name;
  if (member.computed && member.property.type === 'Literal') return String(member.property.value);
  return null; // computed with a runtime key: every property is a candidate
}

function propertyValues(obj, key) {
  const out = [];
  let complete = true;
  for (const p of obj.properties) {
    if (p.type !== 'Property') { complete = false; continue; } // spread
    if (key === null) { out.push(p.value); continue; }
    const k = p.computed ? null : p.key.type === 'Identifier' ? p.key.name : String(p.key.value);
    if (k === key) out.push(p.value);
  }
  return { nodes: out, complete };
}

function evalObjects(ctx, node, depth) {
  if (!node || depth > 8) return { objs: [], complete: false };
  switch (node.type) {
    case 'ObjectExpression':
      return { objs: [node], complete: true };
    case 'Identifier': {
      const init = soleInit(ctx.refs.get(node));
      return init ? evalObjects(ctx, init, depth + 1) : { objs: [], complete: false };
    }
    case 'MemberExpression': {
      const base = evalObjects(ctx, node.object, depth + 1);
      const key = propertyKey(node);
      const out = { objs: [], complete: base.complete };
      for (const o of base.objs) {
        const pv = propertyValues(o, key);
        if (!pv.complete) out.complete = false;
        for (const v of pv.nodes) {
          const r = evalObjects(ctx, v, depth + 1);
          out.objs.push(...r.objs);
          if (!r.complete) out.complete = false;
        }
      }
      return out;
    }
    case 'ConditionalExpression':
    case 'LogicalExpression': {
      const parts = node.type === 'ConditionalExpression' ? [node.consequent, node.alternate] : [node.left, node.right];
      const rs = parts.map(p => evalObjects(ctx, p, depth + 1));
      return { objs: rs.flatMap(r => r.objs), complete: rs.every(r => r.complete) };
    }
  }
  return { objs: [], complete: false };
}

function evalStrings(ctx, node, depth = 0) {
  if (!node || depth > 8) return FAIL();
  const lit = literalString(node);
  if (lit !== null) return single(lit);
  switch (node.type) {
    case 'Identifier': {
      const v = ctx.refs.get(node);
      if (!v) return FAIL();
      if (v.defs.length === 1 && v.defs[0].type === 'ImportBinding') {
        const t = resolveTarget(targetOf(ctx.chunkIndex, ctx.refs, node));
        return t?.kind === 'string' ? single(t.value) : FAIL();
      }
      const init = soleInit(v);
      return init ? evalStrings(ctx, init, depth + 1) : FAIL();
    }
    case 'ConditionalExpression':
      return union([evalStrings(ctx, node.consequent, depth + 1), evalStrings(ctx, node.alternate, depth + 1)]);
    case 'LogicalExpression':
      return union([evalStrings(ctx, node.left, depth + 1), evalStrings(ctx, node.right, depth + 1)]);
    case 'SequenceExpression':
      return evalStrings(ctx, node.expressions[node.expressions.length - 1], depth + 1);
    case 'TemplateLiteral': {
      const parts = [];
      node.quasis.forEach((q, i) => {
        parts.push(single(q.value.cooked));
        if (i < node.expressions.length) parts.push(evalStrings(ctx, node.expressions[i], depth + 1));
      });
      return concat(parts);
    }
    case 'BinaryExpression':
      if (node.operator !== '+') return FAIL();
      return concat([evalStrings(ctx, node.left, depth + 1), evalStrings(ctx, node.right, depth + 1)]);
    case 'CallExpression': {
      if (node.callee.type !== 'Identifier' || node.arguments.length > 0) return FAIL();
      const fn = boundFunction(ctx.refs.get(node.callee));
      if (!fn) return FAIL();
      const rets = returnExpressions(fn);
      return rets.length ? union(rets.map(r => evalStrings(ctx, r, depth + 1))) : FAIL();
    }
    case 'MemberExpression': {
      const base = evalObjects(ctx, node.object, depth + 1);
      const key = propertyKey(node);
      const rs = [];
      for (const o of base.objs) {
        const pv = propertyValues(o, key);
        if (!pv.complete) rs.push(FAIL());
        for (const v of pv.nodes) rs.push(evalStrings(ctx, v, depth + 1));
      }
      if (rs.length === 0) return FAIL();
      const r = union(rs);
      if (!base.complete) r.complete = false;
      return r;
    }
  }
  return FAIL();
}

// ---------------------------------------------------------------------------
// Pass 1: find the accessor family
//
// No accessor is found by name. A root accessor is a function whose parameter
// reaches a GrowthBook client method (`getFeatureValue*`, `checkGate*` —
// property names the minifier leaves alone) as the flag name. A wrapper is a
// function whose parameter reaches an accessor's name slot. Wrappers resolve to
// a fixpoint, across chunks: an accessor imported from another chunk counts.
//
// Cross-chunk imports never rename (the local name is the export name), so an
// imported binding resolves through the exporting chunk's export table. A few
// export names repeat across chunks; the import source is disambiguated by
// intersecting the exporters of every name imported from it.
// ---------------------------------------------------------------------------

const ROOT_METHOD_RE = /^(getFeatureValue\w*|checkGate\w*)$/;
const MAX_ARGS = 4;

const fnKey = (chunk, node) => `${chunk}#${node.start}`;

const chunkInfo = []; // per chunk: exports, importsBySource, fnNames, edges, roots
const exporters = new Map(); // export name → Set<chunk>

// `import.meta.require("/$bunfs/root/chunk-….js")` — Bun's lazy cross-chunk load.
function metaRequireSource(node) {
  if (node?.type !== 'CallExpression') return null;
  const c = node.callee;
  if (c.type !== 'MemberExpression' || c.object.type !== 'MetaProperty' || c.property.name !== 'require') return null;
  const src = literalString(node.arguments[0]);
  return src && src.startsWith('/$bunfs/') ? src : null;
}

const patternKey = p => p.computed ? null : p.key.type === 'Identifier' ? p.key.name : String(p.key.value);

// A chunk namespace: `import * as ns` or `ns = import.meta.require(src)`. Its source, or null.
function namespaceSource(refs, ident) {
  const v = refs.get(ident);
  const def = v && v.defs.length === 1 ? v.defs[0] : null;
  if (!def) return null;
  if (def.type === 'ImportBinding' && def.node.type === 'ImportNamespaceSpecifier') return def.parent.source.value;
  if (def.type === 'Variable' && def.node.id.type === 'Identifier') return metaRequireSource(def.node.init);
  return null;
}

// Resolve an Identifier to a portable target: a function key, an import, or a string.
function targetOf(chunkIdx, refs, ident) {
  const v = refs.get(ident);
  if (!v) return null;
  const def = v.defs.length === 1 ? v.defs[0] : null;
  if (def && def.type === 'ImportBinding' && def.parent.source && def.node.type === 'ImportSpecifier') {
    return { kind: 'import', source: def.parent.source.value, name: def.node.imported.name ?? def.node.imported.value };
  }
  // `{ exportName: local } = import.meta.require(src)`
  if (def && def.type === 'Variable' && def.node.id.type === 'ObjectPattern') {
    const source = metaRequireSource(def.node.init);
    const prop = source && def.node.id.properties.find(p =>
      p.type === 'Property' && (p.value === def.name || (p.value.type === 'AssignmentPattern' && p.value.left === def.name)));
    if (prop && patternKey(prop) !== null) return { kind: 'import', source, name: patternKey(prop) };
  }
  const fn = boundFunction(v);
  if (fn) return { kind: 'fn', key: fnKey(chunkIdx, fn) };
  const str = stringConstant(v);
  if (str !== null) return { kind: 'string', value: str };
  return { kind: 'other' }; // no scope objects retained — they pin the whole chunk
}

// The target of a call's callee: a plain identifier, or `ns.name` on a chunk namespace.
function calleeTarget(chunkIdx, refs, callee) {
  if (callee.type === 'Identifier') return targetOf(chunkIdx, refs, callee);
  if (callee.type === 'MemberExpression' && !callee.computed && callee.object.type === 'Identifier') {
    const source = namespaceSource(refs, callee.object);
    if (source) return { kind: 'import', source, name: callee.property.name };
  }
  return null;
}

const calleeLabel = callee => callee.type === 'Identifier' ? callee.name
  : callee.type === 'MemberExpression' && !callee.computed ? callee.property.name : '<call>';

// An argument as seen from function `fn`: a form over one of fn's parameters,
// or its source text.
function argDescriptor(refs, chunk, node, fn) {
  const f = paramForm(refs, node);
  if (f && f.fn === fn) return { index: f.index, prefix: f.prefix, suffix: f.suffix, prop: f.prop };
  return { text: chunk.text.slice(node.start, node.end).replace(/\s+/g, ' ') };
}

for (const chunk of chunks) {
  const { ast, refs } = parseChunk(chunk);
  const info = {
    exports: new Map(),         // export name → target
    importsBySource: new Map(), // source → Set<name>
    fnNames: new Map(),         // fn key → { name, offset, key } — line resolved on demand
    edges: [],                  // { from, target, args } — a call passing a parameter along
    roots: new Map(),           // fn key → { method, name, def }
    methods: new Set(),         // fn keys of class methods
  };

  eachNode(ast, node => {
    if (node.type === 'ImportDeclaration' && node.source.value.startsWith('/$bunfs/')) {
      const set = info.importsBySource.get(node.source.value) ?? new Set();
      for (const s of node.specifiers) if (s.type === 'ImportSpecifier') set.add(s.imported.name ?? s.imported.value);
      info.importsBySource.set(node.source.value, set);
    } else if (node.type === 'VariableDeclarator' && node.id.type === 'ObjectPattern' && metaRequireSource(node.init)) {
      const source = metaRequireSource(node.init);
      const set = info.importsBySource.get(source) ?? new Set();
      for (const p of node.id.properties) if (p.type === 'Property' && patternKey(p) !== null) set.add(patternKey(p));
      info.importsBySource.set(source, set);
    } else if (node.type === 'ExportNamedDeclaration' && !node.source) {
      for (const s of node.specifiers) {
        const name = s.exported.name ?? s.exported.value;
        info.exports.set(name, targetOf(chunk.index, refs, s.local));
      }
      const d = node.declaration;
      if (d) {
        const ids = d.id ? [d.id] : (d.declarations || []).map(x => x.id).filter(x => x.type === 'Identifier');
        for (const id of ids) {
          const own = d.id ? { kind: 'fn', key: fnKey(chunk.index, d) } : null;
          info.exports.set(id.name, own ?? targetOf(chunk.index, refs, id) ?? { kind: 'other' });
        }
      }
    } else if (node.type === 'MethodDefinition') {
      info.methods.add(fnKey(chunk.index, node.value));
    } else if (isFn(node)) {
      const name = node.id?.name;
      if (name) info.fnNames.set(fnKey(chunk.index, node), { name, offset: node.start, key: chunk.text.slice(node.start, node.id.end) });
    } else if (node.type === 'VariableDeclarator' && isFn(node.init) && node.id.type === 'Identifier') {
      info.fnNames.set(fnKey(chunk.index, node.init), { name: node.id.name, offset: node.start, key: node.id.name });
    } else if (node.type === 'CallExpression' && node.arguments.length > 0) {
      const callee = node.callee;
      if (callee.type === 'MemberExpression' && !callee.computed && ROOT_METHOD_RE.test(callee.property.name)) {
        const f = paramForm(refs, node.arguments[0]);
        if (!f) return;
        const key = fnKey(chunk.index, f.fn);
        const d = node.arguments[1] ? argDescriptor(refs, chunk, node.arguments[1], f.fn) : null;
        info.roots.set(key, {
          method: callee.property.name,
          site: { offset: callee.property.start, key: `${callee.property.name}(` },
          name: { index: f.index, prefix: f.prefix, suffix: f.suffix, prop: f.prop },
          def: d === null ? null : d.text !== undefined ? { text: d.text } : !d.prefix && !d.suffix && !d.prop ? { param: d.index } : { text: '(derived)' },
        });
      } else {
        // Group parameter-derived arguments by the function they come from.
        const fns = new Set();
        for (const a of node.arguments.slice(0, MAX_ARGS)) { const f = paramForm(refs, a); if (f) fns.add(f.fn); }
        if (fns.size === 0) return;
        const t = calleeTarget(chunk.index, refs, callee);
        if (!t || (t.kind !== 'fn' && t.kind !== 'import')) return;
        for (const fn of fns) {
          info.edges.push({
            from: fnKey(chunk.index, fn),
            target: t,
            site: { offset: callee.type === 'Identifier' ? node.start : callee.property.start, key: `${calleeLabel(callee)}(` },
            args: node.arguments.slice(0, MAX_ARGS).map(a => argDescriptor(refs, chunk, a, fn)),
          });
        }
      }
    }
  });

  for (const name of info.exports.keys()) {
    if (!exporters.has(name)) exporters.set(name, new Set());
    exporters.get(name).add(chunk.index);
  }
  chunkInfo.push(info);
}

// Import source → chunk. Intersect the exporters of every name imported from it.
const sourceCandidates = new Map();
for (const info of chunkInfo) {
  for (const [source, names] of info.importsBySource) {
    let cand = sourceCandidates.get(source) ?? null;
    for (const n of names) {
      const ex = exporters.get(n) ?? new Set();
      cand = cand === null ? new Set(ex) : new Set([...cand].filter(c => ex.has(c)));
    }
    sourceCandidates.set(source, cand ?? new Set());
  }
}

// Follow a target to where it is defined: a function key, a string, or null.
function resolveTarget(t, depth = 0) {
  if (!t || depth > 8) return null;
  if (t.kind !== 'import') return t;
  const cand = sourceCandidates.get(t.source);
  let chunk = cand && cand.size === 1 ? [...cand][0] : null;
  if (chunk === null) {
    const ex = exporters.get(t.name);
    if (ex && ex.size === 1) chunk = [...ex][0];
  }
  if (chunk === null) return null;
  return resolveTarget(chunkInfo[chunk].exports.get(t.name), depth + 1);
}

// Compose a wrapper's forms from the accessor it calls and the arguments it passes.
function composeWrapper(accessor, args) {
  const a = args[accessor.name.index];
  if (!a || a.text !== undefined) return null; // name not taken from a parameter
  if (accessor.name.prop && (a.prefix || a.suffix || a.prop)) return null; // property of a derived string
  const name = {
    index: a.index,
    prefix: accessor.name.prefix + a.prefix,
    suffix: a.suffix + accessor.name.suffix,
    prop: accessor.name.prop ?? a.prop,
  };
  let def = accessor.def;
  if (def && def.param !== undefined) {
    const d = args[def.param];
    def = !d ? null
      : d.text !== undefined ? { text: d.text }
      : !d.prefix && !d.suffix && !d.prop ? { param: d.index }
      : { text: '(derived)' };
  }
  return { name, def };
}

// Fixpoint: roots, then anything whose parameter reaches an accessor's name slot.
const accessors = new Map(); // fn key → { chunk, name, def, via, site }
for (const [c, info] of chunkInfo.entries()) {
  for (const [key, root] of info.roots) {
    accessors.set(key, { chunk: c, name: root.name, def: root.def, via: `.${root.method}()`, site: root.site });
  }
}
for (let changed = true; changed;) {
  changed = false;
  for (const [c, info] of chunkInfo.entries()) {
    for (const edge of info.edges) {
      if (accessors.has(edge.from)) continue;
      const r = resolveTarget(edge.target);
      if (!r || r.kind !== 'fn' || !accessors.has(r.key)) continue;
      const composed = composeWrapper(accessors.get(r.key), edge.args);
      if (!composed) continue;
      accessors.set(edge.from, { chunk: c, ...composed, via: r.key, site: edge.site });
      changed = true;
    }
  }
}

const accessorName = key => {
  const a = accessors.get(key);
  return chunkInfo[a.chunk].fnNames.get(key)?.name ?? '<anonymous>';
};

// ---------------------------------------------------------------------------
// Pass 2: read every accessor call site
//
// The name argument is evaluated statically (see evalStrings); a call can name
// more than one flag (`c ? "tengu_a" : "tengu_b"`). A name that is the
// parameter of another accessor is the accessor chain itself, not a read.
// Anything that cannot be followed is reported as `unresolved`: the flags the
// inventory is missing. The default is the argument in the accessor's default
// slot, whitespace-collapsed; async gates take none.
// ---------------------------------------------------------------------------

// A call to a GrowthBook-named method on an object the scanner can't follow:
// the client itself, or a lazily loaded chunk namespace whose public export
// names match (`D().getFeatureValue_SESSION_PINNED` is `Oa` exported).
const DIRECT_CLIENT_CALL = { name: { index: 0, prefix: '', suffix: '', prop: null }, def: { param: 1 } };

// flagName → { defaultsByValue: Map<raw, lineNos[]>, lines: [], accessors: Set, indirect: bool }
// Tracking distinct defaults per call site lets us detect inconsistent usage.
const flags = new Map();
const unresolved = [];
const accessorCalls = new Map(); // fn key → flag reads through it
const accessorSeen = new Set();  // fn keys called directly anywhere, chain included

for (const chunk of chunks) {
  const { ast, refs } = parseChunk(chunk);
  const ctx = { chunkIndex: chunk.index, refs };
  const text = n => chunk.text.slice(n.start, n.end).replace(/\s+/g, ' ');

  eachNode(ast, node => {
    if (node.type !== 'CallExpression') return;
    const callee = node.callee;
    let acc;
    let accKey = null;
    const target = resolveTarget(calleeTarget(chunk.index, refs, callee));
    if (target && target.kind === 'fn' && accessors.has(target.key)) {
      accKey = target.key;
      acc = accessors.get(accKey);
      accessorSeen.add(accKey);
    } else if (callee.type === 'MemberExpression' && !callee.computed && ROOT_METHOD_RE.test(callee.property.name)) {
      acc = DIRECT_CLIENT_CALL; // `D().getFeatureValue_SESSION_PINNED("tengu_…", !1)`
    } else {
      return;
    }
    const label = acc === DIRECT_CLIENT_CALL ? `.${callee.property.name}` : calleeLabel(callee);
    const siteStart = callee.type === 'Identifier' ? node.start : callee.property.start;
    const nameArg = node.arguments[acc.name.index];

    const f = paramForm(refs, nameArg);
    if (f && accessors.has(fnKey(chunk.index, f.fn))) return; // accessor chain

    let r;
    if (!nameArg) r = FAIL();
    else if (acc.name.prop) {
      const objs = evalObjects(ctx, nameArg, 0);
      const rs = objs.objs.map(o => propertyValues(o, acc.name.prop))
        .flatMap(pv => [...pv.nodes.map(v => evalStrings(ctx, v)), ...(pv.complete ? [] : [FAIL()])]);
      r = rs.length ? union(rs) : FAIL();
      if (!objs.complete) r.complete = false;
    } else {
      r = evalStrings(ctx, nameArg);
    }
    const names = [...r.values].map(v => acc.name.prefix + v + acc.name.suffix);

    const lineNo = siteLine(chunk, siteStart, `${calleeLabel(callee)}(`);
    if (!r.complete) {
      unresolved.push({
        accessor: label, line: lineNo, arg: nameArg ? text(nameArg).slice(0, 80) : '',
        ...(names.length ? { partial: names } : {}),
      });
    }
    if (names.length === 0) return;

    if (accKey) accessorCalls.set(accKey, (accessorCalls.get(accKey) ?? 0) + 1);
    const rawDefault = !acc.def ? '(none)'
      : acc.def.text !== undefined ? acc.def.text
      : node.arguments[acc.def.param] ? text(node.arguments[acc.def.param]) : '(none)';
    const indirect = literalString(nameArg) === null || acc.name.prefix !== '' || acc.name.suffix !== '' || acc.name.prop !== null;
    for (const name of names) {
      if (!flags.has(name)) {
        flags.set(name, { defaultsByValue: new Map(), lines: [], accessors: new Set(), indirect: false });
      }
      const entry = flags.get(name);
      if (!entry.defaultsByValue.has(rawDefault)) entry.defaultsByValue.set(rawDefault, []);
      entry.defaultsByValue.get(rawDefault).push(lineNo);
      entry.lines.push(lineNo);
      entry.accessors.add(label);
      if (indirect) entry.indirect = true;
    }
  });
}

// An accessor nothing calls by name is invoked dynamically (a method on a table,
// a callback), so the names it reads arrive at runtime. Report it rather than
// let it pass silently as part of the chain. Class methods are skipped: those
// are the GrowthBook client's own internals, reached through the accessors.
for (const [key, a] of accessors) {
  if (accessorSeen.has(key) || chunkInfo[a.chunk].methods.has(key)) continue;
  const f = chunkInfo[a.chunk].fnNames.get(key);
  const chunk = chunks[a.chunk];
  unresolved.push({
    accessor: f?.name ?? '<anonymous>',
    line: f ? siteLine(chunk, f.offset, f.key) : siteLine(chunk, a.site.offset, a.site.key), // anonymous: its inner accessor call
    arg: describeForm(a.name),
    reason: 'accessor never called by name; the flag name is supplied at runtime',
  });
}

if (flags.size === 0) {
  emit({ type: 'error', message: 'No feature flag reads found. Is this a valid cli.js bundle?' });
  process.exit(1);
}

// The main gate: the accessor with the most flag reads. Kept for continuity with
// older inventories; `accessors` carries the whole family.
const accessorList = [...accessors.entries()]
  .map(([key, a]) => ({
    name: accessorName(key),
    line: (f => f ? siteLine(chunks[a.chunk], f.offset, f.key) : null)(chunkInfo[a.chunk].fnNames.get(key)),
    via: a.via.startsWith('.') ? a.via : accessorName(a.via),
    nameFrom: describeForm(a.name),
    calls: accessorCalls.get(key) ?? 0,
  }))
  .filter(a => a.calls > 0)
  .sort((a, b) => b.calls - a.calls || a.name.localeCompare(b.name));

const gateFunction = accessorList[0].name;

emit({ type: 'gate_function', name: gateFunction, callCount: accessorList[0].calls });
emit({ type: 'accessors', accessors: accessorList });

// Derive a canonical default per flag (the value with the most call sites;
// tie-break alphabetically so it's stable). Used for diff comparison.
function canonicalDefault(entry) {
  return [...entry.defaultsByValue.entries()]
    .sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]))[0][0];
}

// ---------------------------------------------------------------------------
// Classify defaults (used only for grouping the default_shapes header)
// ---------------------------------------------------------------------------

function classifyDefault(raw) {
  if (raw === '!0' || raw === '!1') return 'boolean';
  if (raw === 'null')               return 'null';
  if (raw === '""' || raw === "''") return 'empty-string';
  if (raw === '{}')                 return 'empty-object';
  if (raw === '[]')                 return 'empty-array';
  if (/^-?\d+(\.\d+)?$/.test(raw)) return 'number';
  if (/^["'`]/.test(raw))           return 'string';
  if (raw === '(none)')             return 'none'; // async gates take no default
  if (/^[$\w]+$/.test(raw))        return 'variable'; // minified identifier — value is server-pushed
  return 'expression'; // call or compound — computed at runtime
}

// Minified names change every build; a default of this class carries no signal.
const isNoiseClass = cls => cls === 'variable' || cls === 'expression';

// ---------------------------------------------------------------------------
// Emit default_shapes header
//
// Groups non-boolean defaults by class with their unique raw values, emitted
// once at the top so readers know what e.g. "CI6" means without per-entry noise.
// ---------------------------------------------------------------------------

const shapeGroups = {};
for (const [, info] of flags) {
  for (const raw of info.defaultsByValue.keys()) {
    const cls = classifyDefault(raw);
    if (cls === 'boolean') continue; // !0 / !1 are self-explanatory
    if (!shapeGroups[cls]) shapeGroups[cls] = new Set();
    shapeGroups[cls].add(raw);
  }
}

// Emit only classes that actually appear
const shapesOut = {};
for (const [cls, vals] of Object.entries(shapeGroups)) {
  shapesOut[cls] = [...vals].sort();
}

if (Object.keys(shapesOut).length > 0) {
  emit({ type: 'default_shapes', shapes: shapesOut });
}

// ---------------------------------------------------------------------------
// Emit flags (only when not diffing — diff mode replaces this with its own output)
// ---------------------------------------------------------------------------

const sortedFlags = [...flags.entries()].sort(([a], [b]) => a.localeCompare(b));

if (!diffFile) {
  for (const [name, info] of sortedFlags) {
    const isInconsistent = info.defaultsByValue.size > 1;
    if (isInconsistent) {
      // Multiple distinct defaults across call sites — highlight the breakdown.
      emit({
        type: 'flag',
        name,
        inconsistentDefaults: [...info.defaultsByValue.entries()]
          .sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]))
          .map(([def, lns]) => ({ default: def, occurrences: lns.length, lines: lns })),
        occurrences: info.lines.length,
        lines: info.lines,
        accessors: [...info.accessors].sort(),
      });
    } else {
      emit({
        type: 'flag',
        name,
        default: canonicalDefault(info),
        occurrences: info.lines.length,
        lines: info.lines,
        accessors: [...info.accessors].sort(),
        ...(info.indirect ? { indirect: true } : {}),
      });
    }
  }
}

// Accessor calls whose flag name could not be resolved statically. Each is a
// flag the inventory is missing — the count should stay at or near zero.
for (const u of unresolved) emit({ type: 'unresolved', ...u });

// ---------------------------------------------------------------------------
// Save inventory (line numbers are informational — they shift every version)
// ---------------------------------------------------------------------------

const inventory = {
  version: 'unknown',
  scannedAt: new Date().toISOString(),
  gateFunction,
  lineSource,
  accessors: accessorList,
  defaultShapes: shapesOut,
  flags: Object.fromEntries(
    sortedFlags.map(([name, info]) => [name, {
      default: canonicalDefault(info),
      defaultClass: classifyDefault(canonicalDefault(info)),
      occurrences: info.lines.length,
      lines: info.lines,
      accessors: [...info.accessors].sort(),
      ...(info.indirect ? { indirect: true } : {}),
    }])
  ),
  unresolved,
};

const versionMatch = content.match(/VERSION:\s*"([^"]+)"/);
if (versionMatch) inventory.version = versionMatch[1];

if (saveFile) {
  try {
    fs.writeFileSync(saveFile, JSON.stringify(inventory, null, 2));
    emit({ type: 'saved', file: saveFile, flagCount: flags.size });
  } catch (err) {
    emit({ type: 'error', message: `Cannot write ${saveFile}: ${err.message}` });
  }
}

// ---------------------------------------------------------------------------
// Diff vs previous inventory
//
// Output shape:
//   diff_meta  — versions and counts summary
//   diff_removed — string list of flags gone in current
//   flag (type=flag) — one entry per added/changed flag in standard format,
//                      with a `change` field ("added" | "default_changed" |
//                      "occurrences_changed") and `previousDefault` /
//                      `previousOccurrences` where relevant.
// ---------------------------------------------------------------------------

if (diffFile) {
  let prev;
  try {
    prev = JSON.parse(fs.readFileSync(diffFile, 'utf8'));
  } catch (err) {
    emit({ type: 'error', message: `Cannot read diff file ${diffFile}: ${err.message}` });
    process.exit(1);
  }

  const prevFlags = prev.flags ?? {};
  const currNames = new Set(flags.keys());
  const prevNames = new Set(Object.keys(prevFlags));

  const removed = [...prevNames].filter(n => !currNames.has(n)).sort();

  // Collect added + changed flags as annotated flag entries
  const diffFlags = [];

  for (const [name, info] of sortedFlags) {
    if (!prevNames.has(name)) {
      diffFlags.push({ name, info, change: 'added' });
    } else {
      const prev_ = prevFlags[name];
      const currDef = canonicalDefault(info);
      const currClass = classifyDefault(currDef);
      const prevClass = prev_.defaultClass ?? classifyDefault(prev_.default);
      // Variable-to-variable renames are minifier noise — ignore them.
      // Only flag when the semantic class changes, or when both are the same
      // non-variable class but the value itself differs (e.g. !1 → !0).
      const classChanged = currClass !== prevClass && !(isNoiseClass(currClass) && isNoiseClass(prevClass));
      const valueChanged = !isNoiseClass(currClass) && currDef !== prev_.default;
      if (classChanged || valueChanged) {
        diffFlags.push({ name, info, change: 'default_changed', previousDefault: prev_.default });
      } else if (info.lines.length !== prev_.occurrences) {
        diffFlags.push({ name, info, change: 'occurrences_changed', previousOccurrences: prev_.occurrences });
      }
    }
  }

  emit({
    type: 'diff_meta',
    fromVersion: prev.version ?? 'unknown',
    toVersion: inventory.version,
    addedCount: diffFlags.filter(f => f.change === 'added').length,
    removedCount: removed.length,
    changedCount: diffFlags.filter(f => f.change !== 'added').length,
  });

  if (removed.length > 0) {
    emit({ type: 'diff_removed', flags: removed });
  }

  for (const { name, info, change, previousDefault, previousOccurrences } of diffFlags) {
    const entry = {
      type: 'flag',
      name,
      default: canonicalDefault(info),
      occurrences: info.lines.length,
      lines: info.lines,
      change,
    };
    if (previousDefault !== undefined)    entry.previousDefault    = previousDefault;
    if (previousOccurrences !== undefined) entry.previousOccurrences = previousOccurrences;
    emit(entry);
  }
}

// ---------------------------------------------------------------------------
// Summary
// ---------------------------------------------------------------------------

const defaultOn  = sortedFlags.filter(([, i]) => canonicalDefault(i) === '!0').length;
const defaultOff = sortedFlags.filter(([, i]) => canonicalDefault(i) === '!1').length;
const other      = sortedFlags.length - defaultOn - defaultOff;

emit({
  type: 'summary',
  version: inventory.version,
  gateFunction,
  accessorCount: accessorList.length,
  total: flags.size,
  defaultOn,
  defaultOff,
  otherDefault: other,
  unresolved: unresolved.length,
  ...(lineMapMisses ? { lineMapMisses } : {}),
});
